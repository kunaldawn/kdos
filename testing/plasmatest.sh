# The QML of one port to lint: what it installs, and what of its source it
# does not install as it is; all of its source when it did not build.
port_qml() {          # <portdir>
    local n d=$1 f h
    n=$(basename "$d")
    if [ -z "${BUILT[$n]:-}" ]; then
        find "$d" -name '*.qml' -type f
        return
    fi
    find "${BUILT[$n]}" -name '*.qml' -type f > "$W/qml.installed"
    xargs -r sha256sum < "$W/qml.installed" | cut -d' ' -f1 | LC_ALL=C sort -u > "$W/qml.hashes"
    cat "$W/qml.installed"
    find "$d" -name '*.qml' -type f | while read -r f; do
        h=$(sha256sum "$f" | cut -d' ' -f1)
        grep -qxF "$h" "$W/qml.hashes" || printf '%s\n' "$f"
    done
}

