# ---------------------------------
#   testing/plasmatest.sh — the Qt half of the regression net
#
#   testing/plasmatest.sh [--selftest] [--keep] [<port>...]
#   testing/devdeps-image.sh plasmatest          (or: make plasmatest)
#
# testing/selftest.sh holds KDOS's C to a bare host; this holds its Qt code,
# which no bare host can build. It runs only where Qt 6, KDE Frameworks 6 and
# Plasma's development files are installed — the development image
# (testing/Dockerfile.devdeps) — and anywhere else it refuses, naming what is
# missing, rather than skip and read as a pass.
#
# The ports it builds are the desktop's: every src/ port that is Qt code (its
# CMakeLists.txt finds ECM, Qt 6 or a Framework) or ships Plasma packages (its
# source holds QML, a metadata.json or an SDDM theme's metadata.desktop), and
# every src/art and src/desktop port those depend on, which is where the
# generators of a look-and-feel, a colour scheme or a wallpaper live. A daemon
# or a system tool they need only at run time is selftest.sh's, and is not
# built here.
#
# Four stages, each a failure of its own:
#
#   1. build and QtTest. Each port is built by its own build.sh, with the one
#      change that its cmake configure gets -D BUILD_TESTING=ON, and its tests
#      run under ctest --output-on-failure: headless (QT_QPA_PLATFORM=offscreen),
#      with a fresh HOME and runtime directory, and each test on a session bus
#      of its own (dbus-run-session as CMAKE_TEST_LAUNCHER) — tests that serve
#      fakes of the same D-Bus name run in parallel without taking it from
#      each other. Ports build in the order their depends put them, each
#      seeing the ones before it on CMAKE_PREFIX_PATH and PATH.
#   2. plugins. Every plugin a port installs under lib/qt6/plugins is loaded
#      with QPluginLoader: a missing symbol, a library the image lacks or
#      metadata with no KPlugin.Name is a plugin Plasma drops without a word.
#   3. packages. Every KPackage a port installs — each look-and-feel, desk,
#      Plasma style, plasmoid, KWin script and effect — is installed with
#      kpackagetool6 into a scratch package root under its KPackageStructure;
#      an SDDM theme is checked for the metadata.desktop and main script
#      sddm-greeter loads, and copied into a scratch themes directory the way
#      sddm-kcm installs one. A complete package in the source of a port this
#      run did not build (metadata.json beside contents/) is installed from
#      the source.
#   4. qmllint. Every QML file a port installs, every QML file of its source
#      it does not install as it is (a KCM's, compiled into its plugin), and
#      every QML file of a port not built, is linted against the installed QML
#      modules and the ones the ports just built. A context property (a KCM's
#      `kcm`, the greeter's `sddm`) and a type a C++ plugin registers at run
#      time cannot be resolved by reading the file, so unqualified access,
#      unresolved types and unused imports are reported without failing. A
#      module its host program registers in C++ and installs no qmldir for
#      (HOST_MODULES in the linter below) cannot be read at all, so in a file
#      that imports it, what qmllint says of that module and of the types read
#      through its alias is let through by name. A file a port copied from an
#      upstream package is upstream's, and so is a line of one it changed
#      that the upstream file has word for word (the linter's comment says
#      how both are told apart). Everything else qmllint finds fails, any
#      other import that does not resolve included. The desk layout scripts
#      are checked by node.
#
# Naming ports runs stages 1-3 for those and the ports they are generated by,
# and stage 4 for their QML. --keep leaves the scratch tree and prints where
# it is. --selftest runs the pipeline on testing/fixtures/plasmatest, where
# every stage must pass its good case and fail its bad one.

set -u
cd "$(dirname "$0")/.."
ROOT=$PWD

selftest=0 keep=0 only=()
for a in "$@"; do
    case "$a" in
        --selftest) selftest=1 ;;
        --keep)     keep=1 ;;
        -h|--help)  awk 'NR >= 9 && !/^#/ { exit } NR >= 9 { sub(/^# ?/, ""); print }' "$0"; exit 0 ;;
        -*)         echo "plasmatest: unknown option $a" >&2; exit 2 ;;
        *)          only+=("$a") ;;
    esac
done

[ -d src ] && [ -f src/libs/selftest.c ] || { echo "plasmatest: $ROOT is not a KDOS checkout" >&2; exit 2; }

QMLLINT=$(command -v qmllint6 || command -v qmllint || { [ -x /usr/lib/qt6/bin/qmllint ] && echo /usr/lib/qt6/bin/qmllint; })
missing=""
for t in cmake ctest dbus-run-session kpackagetool6 c++ pkg-config python3; do
    command -v "$t" >/dev/null 2>&1 || missing="$missing $t"
done
[ -n "$QMLLINT" ] || missing="$missing qmllint"
command -v ninja >/dev/null 2>&1 || command -v samu >/dev/null 2>&1 || missing="$missing ninja"
pkg-config --exists Qt6Core 2>/dev/null || missing="$missing Qt6Core.pc"
[ -n "$(ls /usr/lib*/cmake/ECM /usr/share/ECM 2>/dev/null)" ] || missing="$missing extra-cmake-modules"
if [ -n "$missing" ]; then
    echo "plasmatest: this host lacks the Qt and KDE development tools:$missing" >&2
    echo "plasmatest: it runs in the development image — testing/devdeps-image.sh plasmatest" >&2
    exit 2
fi

W=$(mktemp -d "${TMPDIR:-/tmp}/plasmatest.XXXXXX")
if [ "$keep" = 1 ]; then echo "plasmatest: scratch tree $W"
else trap 'rm -rf "$W"' EXIT; fi
mkdir -p "$W/home" "$W/run" "$W/root" "$W/logs"
chmod 700 "$W/run"

fails=0
ok()  { printf '  ok    %s\n' "$*"; }
nb()  { printf '  note  %s\n' "$*"; }
bad() { fails=$((fails + 1)); printf '  FAIL  %s\n' "$*"; }

JOBS=$(nproc 2>/dev/null || echo 2)
export CC=${CC:-gcc} CXX=${CXX:-g++}
export CFLAGS="${CFLAGS:--O2 -pipe -fPIC}" CXXFLAGS="${CXXFLAGS:--O2 -pipe -fPIC}"
export LDFLAGS="${LDFLAGS:--Wl,-O1,--as-needed}"
export SOURCE_DATE_EPOCH=1735689600 TZ=UTC LC_ALL=C.UTF-8
# The checkout is mounted into the image: a build script's Python must not
# leave root's __pycache__ in the source tree.
export PYTHONDONTWRITEBYTECODE=1
export KDOS_JOBS=$JOBS CMAKE_BUILD_PARALLEL_LEVEL=$JOBS MAKEFLAGS=-j$JOBS

# The session every test and every tool here sees: nothing of whoever ran
# the suite, and no display. session_env sets it; session adds a session bus
# of the command's own.
session_env() {
    env HOME="$W/home" XDG_RUNTIME_DIR="$W/run" XDG_CONFIG_HOME="$W/home/.config" \
        XDG_DATA_HOME="$W/home/.local/share" XDG_CACHE_HOME="$W/home/.cache" \
        QT_QPA_PLATFORM=offscreen QT_QUICK_BACKEND=software QT_LOGGING_RULES='*.debug=false' \
        LD_LIBRARY_PATH="${PT_LIBS:-}" QT_PLUGIN_PATH="${PT_PLUGINS:-}" \
        QML_IMPORT_PATH="${PT_QML:-}" QML2_IMPORT_PATH="${PT_QML:-}" \
        PATH="${PT_PATH:+$PT_PATH:}$PATH" \
        "$@"
}
session() { session_env dbus-run-session -- "$@"; }

key() { sed -n "s/^$2[[:blank:]]*=[[:blank:]]*//p" "$1/kpkgbuild" | head -1; }

# A Qt port: a recipe, a build.sh and a CMakeLists.txt that finds ECM, Qt 6
# or a Framework.
is_qt_port() {
    [ -f "$1/kpkgbuild" ] && [ -f "$1/build.sh" ] && [ -f "$1/CMakeLists.txt" ] &&
        grep -qE 'find_package\((ECM|Qt6|KF6)' "$1/CMakeLists.txt"
}

# A port that ships Plasma packages or QML, whatever builds it: its source
# holds QML or a package's metadata, or its build.sh installs into a directory
# Plasma, KWin or SDDM loads packages from (a greeter made from Breeze's at
# build time carries none of its own). find and grep are the image's busybox
# ones, so no GNU-only option is used.
ships_packages() {
    [ -f "$1/kpkgbuild" ] && [ -f "$1/build.sh" ] || return 1
    [ -n "$(find "$1" \( -name '*.qml' -o -name metadata.json \) -type f 2>/dev/null | head -1)" ] ||
        [ -n "$(find "$1" -name metadata.desktop -type f -exec grep -l '^\[SddmGreeterTheme\]' {} + 2>/dev/null)" ] ||
        grep -qE 'share/(sddm/themes|plasma|kwin)/' "$1/build.sh"
}

# The ports and every src/art and src/desktop port they depend on, one
# absolute directory a line.
with_generators() {
    python3 - "$ROOT" "$@" <<'PYEOF'
import glob, os, re, sys
root = sys.argv[1]
ours = {}
for kp in glob.glob(os.path.join(root, "src", "*", "*", "kpkgbuild")):
    d = os.path.dirname(kp)
    if os.path.basename(os.path.dirname(d)) in ("art", "desktop"):
        ours[os.path.basename(d)] = d
def deps(d):
    with open(os.path.join(d, "kpkgbuild"), encoding="utf-8") as f:
        m = re.search(r"^depends[ \t]*=[ \t]*(.*)$", f.read(), re.M)
    return m.group(1).split() if m else []
seen, todo = set(), [os.path.abspath(p) for p in sys.argv[2:]]
while todo:
    d = todo.pop()
    if d in seen:
        continue
    seen.add(d)
    todo += [os.path.abspath(ours[n]) for n in deps(d) if n in ours]
print("\n".join(sorted(seen)))
PYEOF
}

# Ports in the order their depends put them: a port after every port of the
# set it names.
port_order() {
    python3 - "$@" <<'PYEOF'
import os, re, sys
dirs = {os.path.basename(d.rstrip("/")): d for d in sys.argv[1:]}
deps = {}
for n, d in dirs.items():
    with open(os.path.join(d, "kpkgbuild"), encoding="utf-8") as f:
        m = re.search(r"^depends[ \t]*=[ \t]*(.*)$", f.read(), re.M)
    deps[n] = [x for x in (m.group(1).split() if m else []) if x in dirs and x != n]
done, out = set(), []
def visit(n, stack=()):
    if n in done or n in stack:
        return
    for d in deps[n]:
        visit(d, stack + (n,))
    done.add(n)
    out.append(dirs[n])
for n in sorted(dirs):
    visit(n)
print("\n".join(out))
PYEOF
}

# Builds one port with its tests on and runs them. The port's build.sh runs
# as the build runs it — cwd its work directory, $PKG its staging root,
# $PORT_SRC its source, every command under set -e — with cmake wrapped so
# that a configure gets BUILD_TESTING=ON and its build directory is remembered
# for ctest. It runs in a bash of its own: a subshell would inherit the caller's
# `|| r=1`, under which bash ignores set -e, and a failed configure would roll
# on to an install that "succeeds".
cat > "$W/runbuild.sh" <<'RUNEOF'
set -e
d=$1 w=$2
cd "$w/work"
key() { sed -n "s/^$2[[:blank:]]*=[[:blank:]]*//p" "$1/kpkgbuild" | head -1; }
name=$(key "$d" name) version=$(key "$d" version) release=$(key "$d" release)
PKG=$w/pkg PORT_SRC=$d SRC=$w/work SRC_ROOT=$w/work
PKGNAME="$name-$version-$release.tar.xz"
export PKG PORT_SRC SRC SRC_ROOT PKGNAME name version release
cmake() {
    local a b="" prev=""
    case "${1:-}" in --build|--install|-E|-P) command cmake "$@"; return ;; esac
    for a in "$@"; do
        case "$prev" in -B) b=$a ;; esac
        case "$a" in -B?*) b=${a#-B} ;; esac
        prev=$a
    done
    if [ -n "$b" ]; then
        mkdir -p "$b"
        (cd "$b" && pwd) >> "$w/builddirs"
    fi
    command cmake "$@" -D BUILD_TESTING=ON "-DCMAKE_TEST_LAUNCHER=dbus-run-session;--"
}
. "$d/build.sh"
RUNEOF
build_and_test() {     # <portdir> -> 0 built and tested, 1 a test failed, 2 no build
    local d n w log rc
    d=$(cd "$1" && pwd)
    n=$(basename "$d")
    w=$W/ports/$n
    log=$W/logs/$n.build.log
    rm -rf "$w"
    mkdir -p "$w/work" "$w/pkg"
    CMAKE_PREFIX_PATH="${PT_PREFIX:-}" PATH="${PT_PATH:+$PT_PATH:}$PATH" \
        LD_LIBRARY_PATH="${PT_LIBS:-}" bash "$W/runbuild.sh" "$d" "$w" > "$log" 2>&1
    rc=$?
    if [ "$rc" != 0 ]; then
        bad "$n: build.sh failed (exit $rc)"
        { grep -E 'CMake Error|error:|Could NOT find|FAILED:|undefined reference|No such file|command not found' "$log" | head -4
          tail -2 "$log"; } | cut -c1-200 | sed 's/^/        /'
        [ "$keep" = 1 ] && echo "        log: $log"
        return 2
    fi
    local bd tested=0 r=0
    for bd in $(sort -u "$w/builddirs" 2>/dev/null); do
        [ -f "$bd/CTestTestfile.cmake" ] || continue
        session_env ctest --test-dir "$bd" --output-on-failure --timeout 180 -j "$JOBS" \
            > "$W/logs/$n.ctest.log" 2>&1
        if grep -q 'No tests were found' "$W/logs/$n.ctest.log"; then continue; fi
        tested=1
        if grep -q '100% tests passed' "$W/logs/$n.ctest.log"; then
            ok "$n: $(grep -E 'tests passed' "$W/logs/$n.ctest.log" | tail -1 | sed 's/^ *//')"
        else
            bad "$n: $(grep -E 'tests passed|tests failed' "$W/logs/$n.ctest.log" | tail -1 | sed 's/^ *//')"
            grep -E '^\s*[0-9]+ - |FAIL!|QFATAL|Loc:' "$W/logs/$n.ctest.log" | head -12 | sed 's/^/        /'
            [ "$keep" = 1 ] && echo "        log: $W/logs/$n.ctest.log"
            r=1
        fi
    done
    [ "$tested" = 1 ] || nb "$n: built; it has no QtTest suite"
    return $r
}

# Every plugin a port installed must load.
PLUGINCHECK=""
plugincheck_build() {
    cat > "$W/plugincheck.cpp" <<'CPPEOF'
#include <QCoreApplication>
#include <QJsonObject>
#include <QPluginLoader>
#include <cstdio>

int main(int argc, char **argv)
{
    QCoreApplication app(argc, argv);
    int bad = 0;
    for (int i = 1; i < argc; ++i) {
        QPluginLoader loader(QString::fromLocal8Bit(argv[i]));
        const QJsonObject md = loader.metaData();
        if (md.isEmpty()) {
            std::printf("%s\tcarries no Qt plugin metadata\n", argv[i]);
            ++bad;
            continue;
        }
        if (!loader.load()) {
            std::printf("%s\tdoes not load: %s\n", argv[i], qPrintable(loader.errorString()));
            ++bad;
            continue;
        }
        const QJsonObject meta = md.value(QStringLiteral("MetaData")).toObject();
        if (meta.contains(QStringLiteral("KPlugin"))
            && meta.value(QStringLiteral("KPlugin")).toObject().value(QStringLiteral("Name")).toString().isEmpty()) {
            std::printf("%s\thas no KPlugin.Name\n", argv[i]);
            ++bad;
        }
    }
    return bad ? 1 : 0;
}
CPPEOF
    # shellcheck disable=SC2046
    c++ -std=c++17 -fPIC -o "$W/plugincheck" "$W/plugincheck.cpp" $(pkg-config --cflags --libs Qt6Core) \
        > "$W/logs/plugincheck.log" 2>&1 && PLUGINCHECK=$W/plugincheck
}

check_plugins() {     # <port name> <pkg root>
    local so
    mapfile -t so < <(find "$2" -path '*/lib*/qt6/plugins/*' -name '*.so' -type f 2>/dev/null | LC_ALL=C sort)
    [ "${#so[@]}" = 0 ] && return 0
    if [ -z "$PLUGINCHECK" ]; then bad "$1: cannot build the plugin loader ($W/logs/plugincheck.log)"; return 1; fi
    if session "$PLUGINCHECK" "${so[@]}" > "$W/logs/$1.plugins.log" 2>&1; then
        ok "$1: ${#so[@]} plugin(s) load"
        return 0
    fi
    while IFS='	' read -r p why; do
        [ -n "$why" ] && bad "$1: ${p#"$2"} $why"
    done < "$W/logs/$1.plugins.log"
    return 1
}

# The structure a package directory installs as: its metadata's
# KPackageStructure, or where the port put it.
pkg_type() {
    local t
    t=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("KPackageStructure",""))' \
        "$1/metadata.json" 2>/dev/null)
    if [ -z "$t" ]; then
        case "$1" in
            */plasma/plasmoids/*)       t=Plasma/Applet ;;
            */plasma/look-and-feel/*)   t=Plasma/LookAndFeel ;;
            */plasma/layout-templates/*) t=Plasma/LayoutTemplate ;;
            */plasma/wallpapers/*)      t=Plasma/Wallpaper ;;
            */plasma/shells/*)          t=Plasma/Shell ;;
            */plasma/desktoptheme/*)    t=Plasma/Theme ;;
            */kwin/scripts/*)           t=KWin/Script ;;
            */kwin/effects/*)           t=KWin/Effect ;;
            */kwin/tabbox/*)            t=KWin/WindowSwitcher ;;
        esac
    fi
    printf '%s\n' "$t"
}

# Each install goes into the package root of where the package came from (a
# port's staging tree or the source), so a package seen both ways is not a
# collision; two ports installing one id into one root is.
TYPES=""
install_package() {   # <label> <dir> [root name] -> 0 installed
    local t id r
    t=$(pkg_type "$2")
    if [ -z "$t" ]; then bad "$1: ${2##*/} has no KPackageStructure and no known place"; return 1; fi
    if ! printf '%s\n' "$TYPES" | grep -qxF "$t"; then
        nb "$1: ${2##*/} is a $t, which no installed package structure handles; its metadata was checked by preflight"
        return 0
    fi
    id=$(python3 -c 'import json,sys; print(json.load(open(sys.argv[1])).get("KPlugin",{}).get("Id",""))' \
         "$2/metadata.json" 2>/dev/null)
    r=$W/root/${3:-ports}/${t//\//_}
    mkdir -p "$r"
    if session kpackagetool6 --type "$t" --install "$2" --packageroot "$r" \
            > "$W/logs/kpkg.$$.log" 2>&1 && [ -n "$id" ] && [ -d "$r/$id" ]; then
        ok "$1: $t ${id} installs"
        return 0
    fi
    bad "$1: kpackagetool6 cannot install ${2#"$ROOT"/} as $t: $(grep -v '^$' "$W/logs/kpkg.$$.log" | tail -1 | cut -c1-160)"
    return 1
}

check_sddm_theme() {  # <label> <dir>
    local main name
    name=$(basename "$2")
    if ! grep -q '^\[SddmGreeterTheme\]' "$2/metadata.desktop" 2>/dev/null; then
        bad "$1: SDDM theme $name has no metadata.desktop with [SddmGreeterTheme]"; return 1
    fi
    main=$(sed -n 's/^MainScript=//p' "$2/metadata.desktop" | head -1)
    main=${main:-Main.qml}
    [ -f "$2/$main" ] || { bad "$1: SDDM theme $name names $main, which it does not carry"; return 1; }
    mkdir -p "$W/root/sddm/themes"
    rm -rf "$W/root/sddm/themes/$name"
    if cp -r "$2" "$W/root/sddm/themes/$name"; then ok "$1: SDDM theme $name installs"
    else bad "$1: cannot copy $name"; return 1; fi
}

packages_of() {       # <pkg root>: the package directories a port installed
    local p
    for p in share/plasma/plasmoids share/plasma/look-and-feel share/plasma/layout-templates \
             share/plasma/wallpapers share/plasma/shells share/plasma/desktoptheme \
             share/kwin/scripts share/kwin/effects share/kwin/tabbox; do
        find "$1/usr/$p" -mindepth 1 -maxdepth 1 -type d 2>/dev/null
    done | LC_ALL=C sort
}

src_packages() {      # <dir>: complete KPackages in a source tree
    find "$1" -name metadata.json -type f 2>/dev/null | while read -r m; do
        d=$(dirname "$m")
        [ -d "$d/contents" ] && grep -q KPackageStructure "$m" && printf '%s\n' "$d"
    done | LC_ALL=C sort
}

# The linter. qmllint reports every file as JSON, and a warning or error that
# is neither demoted to info by the levels below nor a host module's fails.
#
# KDOS answers for the QML it wrote. A port may install a file it copied from
# an upstream package the image has (the KDOS greeter is Breeze's, patched),
# so an installed file is held to the system's QML files of the same name
# under $PT_UPSTREAM (/usr/share and the QML module directory): one identical
# to such a file is upstream's and is not linted. One made from such a file —
# at least eight of its substantive lines, and four in five of them, are the
# upstream file's word for word — has a finding on such a line reported as a
# note. A substantive line is one that is not an import and holds more than
# brackets and eight characters, so a small file of KDOS's own that opens the
# way every plasmoid does is never taken for upstream's, and a finding on an
# import is always KDOS's. Every file under src/ is KDOS's whole.
cat > "$W/qmllint.py" <<'PYEOF'
import hashlib, json, os, re, subprocess, sys

# A module its host program registers in C++ at start-up and installs no
# qmldir for: qmllint cannot read it from any import path, and a file loaded
# by that program is right to import it.
HOST_MODULES = {
    "org.kde.discover": "Discover registers it for its backends' delegates",
    "org.kde.plasma.welcome.private": "plasma-welcome registers it for its pages",
}
LEVELS = ["--unqualified", "info", "--unresolved-type", "info", "--unused-imports", "info",
          "--context-properties", "info", "--deprecated", "info"]
IMPORT = re.compile(r"^[ \t]*import[ \t]+([A-Za-z_][\w.]*)(?:[ \t]+\d[\d.]*)?(?:[ \t]+as[ \t]+(\w+))?", re.M)

qmllint, listfile, root = sys.argv[1:4]
dirs = [d for d in sys.argv[4:] if d]
listed = [os.path.normpath(l.rstrip("\n")) for l in open(listfile, encoding="utf-8") if l.strip()]
UPSTREAM = [d for d in os.environ.get("PT_UPSTREAM", "/usr/share:/usr/lib/qt6/qml").split(":") if d]

_index = None


def upstream_named(base):
    global _index
    if _index is None:
        _index = {}
        for top in UPSTREAM:
            for dirpath, _dirs, names in os.walk(top):
                for n in names:
                    if n.endswith(".qml"):
                        _index.setdefault(n, []).append(os.path.join(dirpath, n))
    return _index.get(base, [])


def substantive(line):
    s = line.strip()
    return len(s) >= 8 and not s.startswith("import ") and re.search(r"[^\s{}()\[\];,]", s) is not None


def lines_of(data):
    return {l.strip() for l in data.decode("utf-8", "replace").splitlines() if substantive(l)}


def upstream_of(path):
    """("copy", None) for a byte-for-byte upstream file, ("made", its lines)
    for one made from an upstream file, (None, None) for KDOS's own."""
    if path.startswith(root + "/"):
        return None, None
    try:
        with open(path, "rb") as f:
            data = f.read()
    except OSError:
        return None, None
    mine, best, score = lines_of(data), None, 0
    for cand in upstream_named(os.path.basename(path)):
        try:
            with open(cand, "rb") as f:
                theirs = f.read()
        except OSError:
            continue
        if theirs == data:
            return "copy", None
        shared = lines_of(theirs)
        if len(mine & shared) > score:
            best, score = shared, len(mine & shared)
    if best is not None and score >= 8 and 5 * score >= 4 * len(mine):
        return "made", best
    return None, None


origin = {f: upstream_of(f) for f in listed}
copies = [f for f in listed if origin[f][0] == "copy"]
files = [f for f in listed if origin[f][0] != "copy"]
upstream_findings = 0


def excuses(path):
