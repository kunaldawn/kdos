	-DCMAKE_INSTALL_PREFIX=/usr -DCMAKE_INSTALL_LIBDIR=lib \
	-DBUILD_SHARED_LIBS=ON \
	-DBUILD_STATIC=OFF \
	-DBUILD_BINARY=ON
cmake --build build
DESTDIR=$PKG cmake --install build
