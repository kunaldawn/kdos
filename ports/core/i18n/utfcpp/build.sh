# Header only. The headers land in /usr/include/utf8cpp and the CMake package
# utf8cpp::utf8cpp in /usr/share/utf8cpp/cmake, a directory find_package
# searches under the prefix, so consumers need no hint.
cmake -S . -B build -G Ninja \
	-DCMAKE_POLICY_VERSION_MINIMUM=3.5 \
	-DCMAKE_BUILD_TYPE=Release \
	-DCMAKE_INSTALL_PREFIX=/usr \
	-DCMAKE_INSTALL_LIBDIR=lib \
	-DUTF8CPP_ENABLE_TESTS=OFF \
	-DUTF8CPP_ENABLE_BENCHMARKS=OFF
cmake --build build
DESTDIR=$PKG cmake --install build
