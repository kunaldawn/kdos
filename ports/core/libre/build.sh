# ITS VERSION IS PINNED TO baresip's AND THAT IS NOT COSMETIC. libre and
# baresip are released together from one project and baresip checks the ABI
# version it was built against at startup — a mismatch is a runtime abort with
# a message about the library version, not a link error, so it survives a
# clean build and fails when somebody tries to make a call.
mkdir -p build && cd build
cmake .. -G Ninja \
	-DCMAKE_POLICY_VERSION_MINIMUM=3.5 \
	-DCMAKE_BUILD_TYPE=Release \
	-DCMAKE_INSTALL_PREFIX=/usr \
	-DCMAKE_INSTALL_LIBDIR=lib \
	-DBUILD_SHARED_LIBS=ON
ninja
DESTDIR=$PKG ninja install
