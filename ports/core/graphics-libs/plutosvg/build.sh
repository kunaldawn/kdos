# plutovg is found as the installed port. Were the probe to fail, CMake would
# build the empty plutovg/ submodule directory of this archive and stop.
# The FreeType integration is what SDL3_ttf uses to render OT-SVG glyphs.
mkdir -p build && cd build
cmake .. -G Ninja \
	-DCMAKE_BUILD_TYPE=Release \
	-DCMAKE_INSTALL_PREFIX=/usr \
	-DCMAKE_INSTALL_LIBDIR=lib \
	-DBUILD_SHARED_LIBS=ON \
	-DPLUTOSVG_ENABLE_FREETYPE=ON \
	-DPLUTOSVG_BUILD_EXAMPLES=OFF
ninja
DESTDIR=$PKG ninja install
