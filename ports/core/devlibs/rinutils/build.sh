# Headers, a pkg-config file and a CMake package, nothing compiled.
# freecell-solver and black-hole-solver find it through the CMake package;
# without it installed, each tries to git-clone its own copy at configure time.
cmake -S . -B build -G Ninja \
	-D CMAKE_INSTALL_PREFIX=/usr \
	-D CMAKE_INSTALL_LIBDIR=lib \
	-D CMAKE_BUILD_TYPE=Release \
	-D WITH_TEST_SUITE=OFF \
	-Wno-dev
cmake --build build
DESTDIR=$PKG cmake --install build
