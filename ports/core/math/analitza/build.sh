# Eigen is optional upstream and silently dropped when absent; without it the
# matrix functions are compiled out, so it is required here.
# KF_SKIP_PO_PROCESSING leaves the translation catalogues out: bundled data is
# English only.
cmake -S . -B build -G Ninja \
	-D CMAKE_INSTALL_PREFIX=/usr \
	-D CMAKE_INSTALL_LIBDIR=lib \
	-D CMAKE_BUILD_TYPE=Release \
	-D KDE_INSTALL_USE_QT_SYS_PATHS=ON \
	-D BUILD_TESTING=OFF \
	-D KF_SKIP_PO_PROCESSING=ON \
	-D CMAKE_REQUIRE_FIND_PACKAGE_Eigen3=ON \
	-Wno-dev
cmake --build build
DESTDIR=$PKG cmake --install build
