# The metadata side panel, the tag and rating editors and the file properties
# page Dolphin shows are this library's. It needs Baloo only as a library: the
# indexer service is off in the baloo port, so tags and ratings are stored in
# extended attributes and read back from them. KF_SKIP_PO_PROCESSING leaves the
# translations out: bundled data is English only.
cmake -S . -B build -G Ninja \
	-D CMAKE_INSTALL_PREFIX=/usr \
	-D CMAKE_INSTALL_LIBDIR=lib \
	-D CMAKE_BUILD_TYPE=Release \
	-D KDE_INSTALL_USE_QT_SYS_PATHS=ON \
	-D BUILD_TESTING=OFF \
	-D KF_SKIP_PO_PROCESSING=ON \
	-Wno-dev
cmake --build build
DESTDIR=$PKG cmake --install build
