# KF_SKIP_PO_PROCESSING leaves every translation out: bundled data is English
# only, and without it each language's catalogue is compiled and installed.
# The indexer service is off: no baloo_file daemon, autostart entry, unit,
# balooctl, or baloosearch/tags KIO workers, which upstream builds only beside
# the indexer. The library and the QML module stay, and an application
# querying baloo finds an empty index.
cmake -S . -B build -G Ninja \
	-D CMAKE_INSTALL_PREFIX=/usr \
	-D CMAKE_INSTALL_LIBDIR=lib \
	-D CMAKE_BUILD_TYPE=Release \
	-D KDE_INSTALL_USE_QT_SYS_PATHS=ON \
	-D BUILD_TESTING=OFF \
	-D BUILD_QCH=OFF \
	-D KF_SKIP_PO_PROCESSING=ON \
	-D BUILD_INDEXER_SERVICE=OFF \
	-D BUILD_EXPERIMENTAL=OFF \
	-Wno-dev
cmake --build build
DESTDIR=$PKG cmake --install build
