# KF_SKIP_PO_PROCESSING leaves every translation out: bundled data is English
# only, and without it each language's catalogue is compiled and installed.
# The KAuth helper that saves files the user cannot write asks polkit for
# auth_admin; with no action granted in 50-kdos.rules the save is refused and
# the file must be edited with sudo. EditorConfig has no port and is optional.
cmake -S . -B build -G Ninja \
	-D CMAKE_INSTALL_PREFIX=/usr \
	-D CMAKE_INSTALL_LIBDIR=lib \
	-D CMAKE_BUILD_TYPE=Release \
	-D KDE_INSTALL_USE_QT_SYS_PATHS=ON \
	-D BUILD_TESTING=OFF \
	-D BUILD_QCH=OFF \
	-D KF_SKIP_PO_PROCESSING=ON \
	-D ENABLE_KAUTH=ON \
	-D CMAKE_DISABLE_FIND_PACKAGE_EditorConfig=ON \
	-Wno-dev
cmake --build build
DESTDIR=$PKG cmake --install build
