# The parser and scanner are generated at build time from cue_parser.y and
# cue_scanner.l, so bison and flex are build dependencies. The test programs
# under t/ are always compiled and never installed.
cmake -B build -G Ninja \
	-DCMAKE_POLICY_VERSION_MINIMUM=3.5 \
	-DCMAKE_BUILD_TYPE=Release \
	-DCMAKE_INSTALL_PREFIX=/usr \
	-DCMAKE_INSTALL_LIBDIR=lib \
	-DBUILD_SHARED_LIBS=ON
ninja -C build
DESTDIR=$PKG ninja -C build install
