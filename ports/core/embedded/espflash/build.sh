# espflash is Espressif's Rust flasher, one binary that drives the ROM
# bootloader on ESP chips over serial; python3-esptool is the Python reference
# tool, the one meshtastic-firmware's flashing scripts drive.
tar xf $PORT_SRC/${name}-vendor-${version}.tar.xz
export CARGO_HOME="$SRC_ROOT/.cargo"
export RUSTFLAGS="-C target-feature=-crt-static"
export CARGO_NET_OFFLINE=true
cargo build --release --frozen --offline --bin espflash
install -Dm755 target/release/espflash $PKG/usr/bin/espflash
