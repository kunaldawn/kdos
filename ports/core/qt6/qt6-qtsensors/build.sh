# The install layout (bin, lib/qt6, include/qt6, mkspecs) is inherited from
# qt6-qtbase through Qt6BuildInternals, so no INSTALL_* path is passed here: a
# path set only in this module would scatter it away from every other one.
#
# sensorfw is the Sailfish sensor daemon, not on this host. The iio-sensor-proxy
# backend speaks D-Bus and is built with QtDBus from qt6-qtbase, but no
# iio-sensor-proxy port exists, so on this system it finds no service and
# QtSensors reports no accelerometer, gyroscope or light sensor.
mkdir build && cd build
cmake .. -G Ninja \
	-DCMAKE_BUILD_TYPE=Release \
	-DCMAKE_INSTALL_PREFIX=/usr \
	-DQT_BUILD_TESTS=OFF \
	-DQT_BUILD_EXAMPLES=OFF \
	-DFEATURE_sensorfw=OFF
ninja
DESTDIR=$PKG ninja install
