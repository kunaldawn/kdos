# ---------------------------------
#   vendor.py — Alpine's security database, pruned into one table
#
# HOST-ONLY, run by hand with network. Nothing on the target and nothing in the
# build ever runs this; what ships is `secdb.txt` beside it, which is committed.
# Same shape as kdos-icons' and kdos-cursors' vendoring, and for the same
# reasons: the prune is a KDOS decision, and the artefact is diffable.
#
# WHY ALPINE. It is the closest distro to KDOS that publishes a machine-readable
# security database: musl, the same upstream tarballs, comparable pins. OSV's
# `Alpine/all.zip` carries the same facts in a heavier form, and NVD is retired
# feeds plus an API — neither answers a question this 270 KB file cannot.
#
# WHAT IT IS NOT. secdb is keyed to ALPINE package names and Alpine's own
# versioning, so a match is a strong hint and never a proof: a port whose name
# differs needs `secdb = <alpine-name>` in its recipe, and a CVE fixed upstream
# in a version Alpine never shipped is invisible here. There is no reliable
# mapping from a source tarball name to CVEs — cve-bin-tool's CPE lookups need a
# human to assert `zlib -> cpe:2.3:a:zlib:zlib` — so this tool reports what
# Alpine recorded and says so.
#
#   usage: vendor.py [branch ...]      (default: the six newest stable branches)
#          vendor.py --corrections     (re-apply corrections.txt to secdb.txt,
#                                       offline, keeping its generation date)
#
# corrections.txt beside this script names rows Alpine recorded under a
# version upstream never released (aerc's `1.21.0` for 0.21.0): such a row is
# above every real version, so it flags every pin for good. Each is rewritten
# to the right version, or dropped, as the table is written. A correction
# that matches no row is reported, because Alpine has fixed the row or
# renamed it and the line should go.
#
# The output is one line per (package, fixed version):
#
#   <alpine-package> <fixed-version> <CVE>[,<CVE>...]
#
# and `kdos cve` reads it with no JSON parser at all.

import json
import os
import sys
import urllib.request
from datetime import datetime, timezone

BASE = "https://secdb.alpinelinux.org"
DEFAULT_BRANCHES = ["v3.19", "v3.20", "v3.21", "v3.22", "v3.23", "v3.24"]
REPOS = ("main", "community")


HERE = os.path.dirname(os.path.abspath(__file__))


def load_corrections():
    fixes = {}
    with open(os.path.join(HERE, "corrections.txt")) as f:
        for line in f:
            line = line.split("#", 1)[0].split()
            if len(line) == 3:
                fixes[(line[0], line[1])] = None if line[2] == "drop" else line[2]
    return fixes


def apply_corrections(rows):
    """rows: [(name, version, cves)] -> the same, corrected, re-merged."""
    fixes = load_corrections()
    used = set()
    merged = {}
    for name, version, cves in rows:
        key = (name, version)
        if key in fixes:
            used.add(key)
            if fixes[key] is None:
                continue
            version = fixes[key]
        merged.setdefault(name, {}).setdefault(version, set()).update(cves)
    for name, version in sorted(set(fixes) - used):
        print(f"  corrections.txt: no row '{name} {version}' — remove the line",
              file=sys.stderr)
    return merged


def write(merged, stamp, sources):
    lines = []
    for name in sorted(merged):
        for version in sorted(merged[name]):
            cves = ",".join(sorted(merged[name][version]))
            lines.append(f"{name} {version} {cves}")
    header = (
        "# KDOS security database — GENERATED by vendor.py; do not edit.\n"
        f"# generated {stamp} from Alpine secdb: {sources}\n"
        "# source https://secdb.alpinelinux.org/ (CC-BY-SA-4.0), with corrections.txt applied\n"
        "# <alpine-package> <version-that-fixed-it> <CVE>[,<CVE>...]\n"
    )
    out = header + "\n".join(lines) + "\n"
    with open(os.path.join(HERE, "secdb.txt"), "w") as f:
        f.write(out)
    print(f"secdb.txt: {len(merged)} packages, {len(lines)} rows, {len(out)} bytes")


def recorrect():
    # Line by line, so every row no correction names stays byte for byte: an
    # identifier list is joined with ',' and some identifiers contain one.
    fixes = load_corrections()
    applied = {(n, v): (n, old) for (n, old), v in fixes.items() if v}
    used = set()
    head, rows = [], []
    with open(os.path.join(HERE, "secdb.txt")) as f:
        for line in f:
            if line.startswith("#"):
                head.append(line.replace(
                    "(CC-BY-SA-4.0)\n", "(CC-BY-SA-4.0), with corrections.txt applied\n"))
                continue
            name, version, cves = line.rstrip("\n").split(" ", 2)
            if (name, version) in fixes:
                used.add((name, version))
                if fixes[(name, version)] is None:
                    continue
                version = fixes[(name, version)]
            elif (name, version) in applied:
                used.add(applied[(name, version)])
            rows.append((name, version, cves))
    if not any(h.startswith("# generated ") for h in head):
        print("secdb.txt has no '# generated' line — refusing", file=sys.stderr)
        return 1
    for name, version in sorted(set(fixes) - used):
        print(f"  corrections.txt: no row '{name} {version}' — remove the line",
              file=sys.stderr)
    rows.sort(key=lambda r: (r[0], r[1]))
    out = "".join(head) + "".join(f"{n} {v} {c}\n" for n, v, c in rows)
    with open(os.path.join(HERE, "secdb.txt"), "w") as f:
        f.write(out)
    print(f"secdb.txt: {len(rows)} rows, {len(out)} bytes")
    return 0


def fetch(url):
    with urllib.request.urlopen(url, timeout=60) as r:
        return r.read()


def main(argv):
    if argv[1:] == ["--corrections"]:
        return recorrect()
    branches = argv[1:] or DEFAULT_BRANCHES
    merged = {}
    got = []

    for branch in branches:
        for repo in REPOS:
            url = f"{BASE}/{branch}/{repo}.json"
            try:
                data = json.loads(fetch(url))
            except Exception as e:               # noqa: BLE001 — report and go on
                print(f"  {branch}/{repo}: {e}", file=sys.stderr)
                continue
            got.append(f"{branch}/{repo}")
            for entry in data.get("packages", []):
                pkg = entry.get("pkg") or {}
                name = pkg.get("name")
                if not name:
                    continue
                fixes = merged.setdefault(name, {})
                for version, cves in (pkg.get("secfixes") or {}).items():
                    fixes.setdefault(version, set()).update(cves)

    if not merged:
        print("nothing fetched — refusing to overwrite secdb.txt", file=sys.stderr)
        return 1

    # Every branch is merged rather than kept separate: a CVE fixed in v3.19 is
    # still a CVE, and a KDOS pin older than that fix is still exposed. The union
    # is what makes an old pin visible at all.
    rows = [(name, version, cves)
            for name in merged for version, cves in merged[name].items()]
    stamp = datetime.now(timezone.utc).strftime("%Y-%m-%d")
    write(apply_corrections(rows), stamp, " ".join(got))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
